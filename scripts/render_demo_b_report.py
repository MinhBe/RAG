from __future__ import annotations

import html
import json
from datetime import UTC, datetime
from pathlib import Path

REPORT_JSON = Path("artifacts/demo_b/security_demo_b_report.json")
REPORT_HTML = Path("artifacts/demo_b/security_demo_b_report.html")


def esc(value: object) -> str:
    return html.escape(str(value), quote=True)


def status_badge(value: str) -> str:
    css = (
        "ok" if value in {"stored", "pending_human_review", "not_required"} else "warn"
    )
    return f'<span class="badge {css}">{esc(value)}</span>'


def render_cases(cases: list[dict]) -> str:
    rows = []
    for case in cases:
        rows.append(
            "<tr>"
            f"<td>{esc(case.get('case_id'))}</td>"
            f"<td>{status_badge(str(case.get('approval_status')))}</td>"
            f"<td>{esc(case.get('findings'))}</td>"
            f"<td>{status_badge(str(case.get('storage_status')))}</td>"
            f"<td><code>{esc(case.get('run_uuid'))}</code></td>"
            "</tr>"
        )
    return "\n".join(rows)


def main() -> None:
    if not REPORT_JSON.exists():
        raise SystemExit(f"missing report json: {REPORT_JSON}")
    report = json.loads(REPORT_JSON.read_text(encoding="utf-8"))
    generated = datetime.now(UTC).isoformat(timespec="seconds")
    providers = report.get("providers", {})
    ai = providers.get("ai_gateway", {})
    html_text = """<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>Hermes Demo B Security Report</title>
  <style>
    body { font-family: Segoe UI, Arial, sans-serif; margin: 40px; color: #17202a; }
    .hero { border: 1px solid #d5dde5; border-radius: 14px; padding: 24px; background: #f8fafc; }
    .grid { display: grid; grid-template-columns: repeat(3, 1fr); gap: 12px; margin: 18px 0; }
    .card { border: 1px solid #d5dde5; border-radius: 10px; padding: 14px; background: white; }
    table { width: 100%; border-collapse: collapse; margin-top: 18px; }
    th, td { text-align: left; border-bottom: 1px solid #e6ebf1; padding: 10px; }
    th { background: #eef3f8; }
    code { background: #eef3f8; padding: 2px 5px; border-radius: 5px; }
    .badge { padding: 4px 8px; border-radius: 999px; font-weight: 600; }
    .ok { background: #e8f6ef; color: #17643a; }
    .warn { background: #fff4df; color: #7a4b00; }
  </style>
</head>
"""
    html_text += f"""
<body>
  <section class="hero">
    <h1>Hermes Demo B Security</h1>
    <p>End-to-end defensive post-audit demo report generated at <code>{esc(generated)}</code>.</p>
    <div class="grid">
      <div class="card"><b>API health</b><br>{status_badge(str(report.get("health", {}).get("status")))}</div>
      <div class="card"><b>AI gateway</b><br>{status_badge("reachable" if ai.get("reachable") else "not reachable")}</div>
      <div class="card"><b>Supabase</b><br>{status_badge("configured" if providers.get("supabase_configured") else "not configured")}</div>
    </div>
  </section>

  <h2>Security cases</h2>
  <table>
    <thead><tr><th>Case</th><th>Approval</th><th>Findings</th><th>Storage</th><th>Run UUID</th></tr></thead>
    <tbody>
      {render_cases(report.get("cases", []))}
    </tbody>
  </table>
"""
    html_text += """
  <h2>Recruiter talking points</h2>
  <ul>
    <li>Prompt-injection text inside logs is treated as evidence data, not as operator instruction.</li>
    <li>High and critical synthetic evidence routes to human review; Hermes does not claim autonomous remediation.</li>
    <li>Every finding is tied to evidence references and persisted for audit readback.</li>
    <li>The report is generated by the same one-command runner used for the live demo.</li>
  </ul>

  <h2>Boundary</h2>
  <p>This is a defensive SOC post-audit demonstration using synthetic/redacted fixtures only.</p>
</body>
</html>
"""
    REPORT_HTML.parent.mkdir(parents=True, exist_ok=True)
    REPORT_HTML.write_text(html_text, encoding="utf-8")
    print(f"PASS Demo B HTML report written to {REPORT_HTML}")


if __name__ == "__main__":
    main()
